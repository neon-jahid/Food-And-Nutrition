/*
 * Runs before `react-router build`. Writes into public/:
 *   sitemap.xml  — every page in both languages, with hreflang alternates
 *   robots.txt   — allows everything, points to the sitemap
 *   _redirects   — permanent (301) redirects for old URLs (Netlify / Cloudflare Pages format)
 *
 * The site URL comes from VITE_SITE_URL (environment or .env file).
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { DEFAULT_LANG, LANGS, LEGACY_REDIRECTS, allPublicPaths, withLang } from "../src/paths.js";

function env(key) {
  if (process.env[key]) return process.env[key];
  for (const file of [".env.production", ".env"]) {
    if (!existsSync(file)) continue;
    const m = readFileSync(file, "utf8").match(new RegExp(`^${key}=(.*)$`, "m"));
    if (m) return m[1].trim().replace(/^["']|["']$/g, "");
  }
  return "";
}

const configured = env("VITE_SITE_URL");
const SITE_URL = (configured || "https://food-and-nutrition.example").replace(/\/$/, "");
if (!configured) {
  console.warn("\n⚠  VITE_SITE_URL is not set — sitemap, canonical and Open Graph URLs use a placeholder domain.\n   Set it in .env before deploying (see docs/DEVELOPMENT_PROGRESS.md).\n");
}

const today = new Date().toISOString().slice(0, 10);
const esc = s => s.replace(/&/g, "&amp;");
const url = (lang, path) => esc(SITE_URL + withLang(lang, path));

const entries = allPublicPaths().flatMap(path =>
  LANGS.map(lang => {
    const alts = [
      ...LANGS.map(l => `    <xhtml:link rel="alternate" hreflang="${l}" href="${url(l, path)}"/>`),
      `    <xhtml:link rel="alternate" hreflang="x-default" href="${url(DEFAULT_LANG, path)}"/>`,
    ].join("\n");
    return `  <url>\n    <loc>${url(lang, path)}</loc>\n    <lastmod>${today}</lastmod>\n${alts}\n  </url>`;
  })
);

writeFileSync(
  "public/sitemap.xml",
  `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">\n${entries.join("\n")}\n</urlset>\n`
);

writeFileSync("public/robots.txt", `User-agent: *\nAllow: /\n\nSitemap: ${SITE_URL}/sitemap.xml\n`);

// Old URLs → English version (visitors who chose Bangla are redirected again client-side via ?lang / saved choice).
const redirects = [
  "# Generated by scripts/generate-seo.mjs — do not edit by hand.",
  "# Old (pre-2026-11) URLs → new bilingual URLs.",
  // ?lang=bn links go to the Bangla version; query-conditioned rules must come first
  ...LEGACY_REDIRECTS.map(([from, to]) => `${from}  lang=bn  ${withLang("bn", to)}  301`),
  ...LEGACY_REDIRECTS.map(([from, to]) => `${from}  ${withLang(DEFAULT_LANG, to)}  301`),
  ...LANGS.flatMap(l =>
    [["/guide", "/food-guide"], ["/storage", "/food-guide/food-storage"], ["/meals", "/food-guide/meal-times"],
     ["/vitamins", "/nutrition/vitamins"], ["/minerals", "/nutrition/minerals"], ["/deficiency", "/nutrition/deficiency"],
     ["/myths", "/food-myths"]].map(([a, b]) => `${withLang(l, a)}  ${withLang(l, b)}  301`)
  ),
];
writeFileSync("public/_redirects", redirects.join("\n") + "\n");

console.log(`SEO files written: ${entries.length} sitemap URLs, ${redirects.length - 2} redirects.`);
